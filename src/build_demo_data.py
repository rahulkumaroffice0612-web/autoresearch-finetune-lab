#!/usr/bin/env python3
"""Bake the real experiment artifacts into web/data.js for the static demo UI.

The demo site is pure static (no backend, no fetch of raw .jsonl), so this
embeds the numbers the UI needs as a single `window.LAZY` object. Re-run after
any experiment change to refresh the site.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "artifacts"
OUT = ROOT / "web" / "data.js"


def load_jsonl(name: str) -> list[dict]:
    return [json.loads(l) for l in (ART / name).read_text().splitlines() if l.strip()]


def runs(arm: str) -> list[dict]:
    out = []
    for r in load_jsonl(f"experiments_arm{arm}.jsonl"):
        sel = r.get("select") or {}
        out.append({
            "run": r.get("run"),
            "kept": bool(r.get("kept")),
            "reason": (r.get("reason") or "").strip(),
            "selectLoss": sel.get("loss"),
            "selectAcc": sel.get("accuracy"),
            "rungEvals": [{"step": e["step"], "loss": e["eval_loss"]} for e in (r.get("rung_evals") or [])],
            "config": {k: r.get("config", {}).get(k) for k in
                       ("freeze_backbone", "lora_r", "lora_alpha", "learning_rate", "label_smoothing", "epochs")
                       if k in r.get("config", {})},
        })
    return out


def main() -> None:
    winner = json.loads((ART / "test_score.json").read_text())
    tinker = json.loads((ART / "tinker_confirm_result.json").read_text())

    data = {
        "results": [
            {"model": "Prior / Uniform", "role": "reference", "acc": 0.470, "kl": None, "brier": None, "ece": None},
            {"model": "Zero-shot base", "role": "no training", "acc": 0.483, "kl": None, "brier": None, "ece": None},
            {"model": "Tinker 4B (confirm)", "role": "cloud referee", "acc": tinker["accuracy"],
             "kl": tinker["kl_from_gold"], "brier": tinker["brier"], "ece": tinker["ece"]},
            {"model": "LazyDecider 0.8B", "role": "winner", "acc": winner["accuracy"],
             "kl": winner["kl_from_gold"], "brier": winner["brier"], "ece": winner["ece"], "winner": True},
        ],
        "armA": runs("A"),
        "armB": runs("B"),
        "links": {
            "repo": "https://github.com/rahulkumaroffice0612-web/autoresearch-finetune-lab",
            "model": "https://huggingface.co/rahulkumar0612/lazydecider-0.8b",
            "dataset": "https://huggingface.co/datasets/LocalLLaMA/typed-decisions",
        },
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// auto-generated by src/build_demo_data.py — do not hand-edit\n"
                   "window.LAZY = " + json.dumps(data, indent=2) + ";\n")
    print(f"wrote {OUT}  ({len(data['armA'])} armA runs, {len(data['armB'])} armB runs)")

    # Keep the static site self-contained: copy the assets it embeds into web/assets/.
    assets = OUT.parent / "assets"
    assets.mkdir(exist_ok=True)
    import shutil
    import subprocess
    for src, dst in [
        (ART / "results_comparison.png", "results_comparison.png"),
        (ART / "gemma_learning_curves.png", "gemma_learning_curves.png"),
        (ART / "demo_audio" / "narration.mp3", "narration.mp3"),
    ]:
        if src.exists():
            shutil.copy2(src, assets / dst)
    # The cover is a 5.5 MB render; downscale for the web hero (falls back to a
    # plain copy if ffmpeg isn't present).
    cover = ART / "lazydecider_cover.png"
    if cover.exists():
        try:
            subprocess.run(
                ["ffmpeg", "-y", "-loglevel", "error", "-i", str(cover),
                 "-vf", "scale=900:-1", str(assets / "lazydecider_cover.png")],
                check=True,
            )
        except (FileNotFoundError, subprocess.CalledProcessError):
            shutil.copy2(cover, assets / "lazydecider_cover.png")
    print(f"copied assets -> {assets}")


if __name__ == "__main__":
    main()
