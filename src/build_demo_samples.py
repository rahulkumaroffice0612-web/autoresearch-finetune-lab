#!/usr/bin/env python3
"""Extract a few real invoice_processing sample cases for the interactive demo.

Pulls human-readable factors + gold labels + the winning model's prediction for a
curated set of sealed invoice cases, and appends them to web/data.js data (via a
separate web/samples.js). Shows the model generalizing to the AP/finance domain
(its best: 0.840 sealed accuracy) on real, legible business decisions.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEALED = ROOT / "data" / "sealed" / "test.jsonl"
PREDS = ROOT / "artifacts" / "test_predictions.jsonl"
OUT = ROOT / "web" / "samples.js"

# Decisions we surface, with friendly labels. Covers both the generic agent
# questions and the invoice-specific ones.
Q_LABELS = {
    "disposition": "Disposition (pay / hold / escalate)",
    "matches_order": "Matches the purchase order?",
    "discrepancy_severity": "Discrepancy severity",
    "duplicate": "Duplicate invoice?",
    "urgency": "Urgency",
    "action": "Recommended action",
    "risk": "Risk score",
    "needs_review": "Needs human review?",
    "outcome": "Likely outcome",
}
# How many invoice cases to feature in the stepper.
N_SAMPLES = 6


def argmax(probs: dict) -> str:
    return max(probs, key=probs.get)


def main() -> None:
    gold_by_id, factors_by_id = {}, {}
    for line in SEALED.read_text().splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        if not r["id"].startswith("invoice_processing"):
            continue
        factors_by_id[r["id"]] = json.loads(r["factors"]) if isinstance(r["factors"], str) else r["factors"]
        gold_by_id[r["id"]] = json.loads(r["gold"]) if isinstance(r["gold"], str) else r["gold"]

    pred_by_id = {}
    for line in PREDS.read_text().splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        if r["id"].startswith("invoice_processing"):
            pred_by_id[r["id"]] = r["answers"]

    # Pick cases with the richest, most legible scenarios: prefer multi-decision
    # cases and variety across issue types. Include at least one miss for honesty.
    ids = sorted(gold_by_id)

    def n_decisions(cid: str) -> int:
        return sum(1 for q in Q_LABELS if q in gold_by_id[cid])

    def n_hits(cid: str) -> int:
        g, p = gold_by_id[cid], pred_by_id.get(cid, {})
        return sum(argmax(g[q]["probabilities"]) == argmax(p.get(q, {}).get("probabilities", {None: 1}))
                   for q in Q_LABELS if q in g)

    # Rank: most decisions first, then variety of issue type.
    ranked = sorted(ids, key=lambda c: (-n_decisions(c), c))
    picked, seen_issues = [], set()
    for cid in ranked:
        issue = factors_by_id[cid].get("issue", "none")
        if issue not in seen_issues or len(picked) < N_SAMPLES:
            if cid not in picked:
                picked.append(cid)
                seen_issues.add(issue)
        if len(picked) >= N_SAMPLES:
            break
    # Ensure at least one imperfect case is included (honest demo).
    if all(n_hits(c) == n_decisions(c) for c in picked):
        for cid in ranked:
            if cid not in picked and n_hits(cid) < n_decisions(cid):
                picked[-1] = cid
                break

    samples = []
    for cid in picked:
        f = factors_by_id[cid]
        gold = gold_by_id[cid]
        pred = pred_by_id.get(cid, {})
        decisions = []
        for qid, label in Q_LABELS.items():
            if qid not in gold:
                continue
            g = argmax(gold[qid]["probabilities"])
            p = argmax(pred.get(qid, {}).get("probabilities", {g: 1.0}))
            pconf = max(pred.get(qid, {}).get("probabilities", {0: 0}).values())
            decisions.append({"label": label, "gold": g, "pred": p,
                              "match": g == p, "conf": round(float(pconf), 3)})
        # A compact, human-readable scenario summary from the factors.
        summary = {
            "Invoice total": f"${f.get('invoice_total_usd', 0):,.2f}",
            "PO total": f"${f.get('po_total_usd', 0):,.2f}",
            "Variance": f"{f.get('variance_pct', 0):+.0f}%  (${f.get('variance_usd', 0):,.2f})",
            "Issue": f.get("issue_description") or f.get("issue") or "none",
            "Payment terms": f.get("payment_terms", "—"),
            "Status": ("overdue" if f.get("overdue") else "on time")
                      + (", delivered" if f.get("delivered") else ", not delivered"),
            "Vendor disputes (12m)": f.get("vendor_disputes_12m", 0),
        }
        hits = sum(d["match"] for d in decisions)
        samples.append({"id": cid, "summary": summary, "decisions": decisions,
                        "hits": hits, "total": len(decisions)})

    OUT.write_text("// auto-generated by src/build_demo_samples.py — do not hand-edit\n"
                   "window.LAZY_SAMPLES = " + json.dumps(samples, indent=2) + ";\n")
    print(f"wrote {OUT}  ({len(samples)} invoice cases)")
    for s in samples:
        print(f"  {s['id']}: {s['hits']}/{s['total']} decisions match gold")


if __name__ == "__main__":
    main()
