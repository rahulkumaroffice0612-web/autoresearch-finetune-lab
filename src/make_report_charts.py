#!/usr/bin/env python3
"""Generate the morning-report charts AND the Gemma reasoning excerpt block.

Figures written to artifacts/:
  1. gemma_learning_curves.png
  2. results_comparison.png
Text written to artifacts/gemma_excerpts.md (verbatim Gemma reasons).

Everything here is derived from on-disk logs; nothing is hand-typed.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ART = Path(__file__).resolve().parent.parent / "artifacts"

# Palette (colour-blind friendly-ish, consistent across both figures).
GEMMA = "#2a6f97"      # Gemma local search
TINKER = "#e76f51"     # Tinker cloud confirm
WINNER = "#2a9d8f"     # LazyDecider 0.8B winner
REF = "#8d99ae"        # published references / baselines


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def fig_learning_curves() -> Path:
    rows = load_jsonl(ART / "experiments_armA.jsonl")
    fig, ax = plt.subplots(figsize=(7.2, 4.6), dpi=150)

    for r in rows:
        evals = r.get("rung_evals") or []
        if not evals:
            continue
        xs = [e["step"] for e in evals]
        ys = [e["eval_loss"] for e in evals]
        kept = r.get("kept")
        label = f"run {r['run']} {'(kept)' if kept else ''}".strip()
        ax.plot(
            xs,
            ys,
            marker="o",
            linewidth=2.2 if kept else 1.3,
            alpha=1.0 if kept else 0.55,
            color=GEMMA if kept else REF,
            label=label,
        )

    ax.set_title("Gemma-driven config search — ASHA select loss per rung", fontsize=12, fontweight="bold")
    ax.set_xlabel("training step (ASHA rung)")
    ax.set_ylabel("select-split eval loss (lower = better)")
    ax.grid(True, linestyle=":", alpha=0.4)
    ax.legend(fontsize=8, ncols=2, framealpha=0.9)
    fig.tight_layout()
    out = ART / "gemma_learning_curves.png"
    fig.savefig(out)
    plt.close(fig)
    return out


def fig_results_comparison() -> Path:
    tinker = json.loads((ART / "tinker_confirm_result.json").read_text())
    winner = json.loads((ART / "test_score.json").read_text())

    # Published reference rows (sealed-test, from the typed-decisions benchmark).
    labels = ["Prior", "Uniform", "Zero-shot", "Tinker 4B\nconfirm", "LazyDecider\n0.8B (ours)"]
    acc = [0.470, 0.470, 0.483, tinker["accuracy"], winner["accuracy"]]
    kl = [None, None, None, tinker["kl_from_gold"], winner["kl_from_gold"]]
    ece = [None, None, None, tinker["ece"], winner["ece"]]
    colors = [REF, REF, REF, TINKER, WINNER]

    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.8), dpi=150)

    # Panel A: accuracy
    ax = axes[0]
    bars = ax.bar(labels, acc, color=colors, edgecolor="black", linewidth=0.5)
    ax.set_title("Sealed-test accuracy", fontsize=12, fontweight="bold")
    ax.set_ylabel("accuracy")
    ax.set_ylim(0, 0.9)
    for b, v in zip(bars, acc):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.012, f"{v:.3f}", ha="center", fontsize=8.5)
    ax.tick_params(axis="x", labelsize=8)
    ax.grid(True, axis="y", linestyle=":", alpha=0.4)

    # Panel B: calibration (KL + ECE) — only where measured.
    ax = axes[1]
    idx = [i for i, v in enumerate(kl) if v is not None]
    xlab = [labels[i] for i in idx]
    klv = [kl[i] for i in idx]
    ecev = [ece[i] for i in idx]
    x = range(len(idx))
    w = 0.38
    b1 = ax.bar([i - w / 2 for i in x], klv, width=w, label="KL from gold", color=GEMMA, edgecolor="black", linewidth=0.5)
    b2 = ax.bar([i + w / 2 for i in x], ecev, width=w, label="ECE", color=TINKER, edgecolor="black", linewidth=0.5)
    ax.set_xticks(list(x))
    ax.set_xticklabels(xlab, fontsize=8)
    ax.set_title("Calibration (lower = better)", fontsize=12, fontweight="bold")
    ax.set_ylabel("KL / ECE")
    for bars, vals in ((b1, klv), (b2, ecev)):
        for bb, v in zip(bars, vals):
            ax.text(bb.get_x() + bb.get_width() / 2, v + 0.004, f"{v:.3f}", ha="center", fontsize=8)
    ax.legend(fontsize=9)
    ax.grid(True, axis="y", linestyle=":", alpha=0.4)

    fig.suptitle(
        "LazyDecider: calibration-per-dollar on a laptop  (Gemma local search → Tinker confirm → 0.8B winner)",
        fontsize=12.5,
        fontweight="bold",
    )
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    out = ART / "results_comparison.png"
    fig.savefig(out)
    plt.close(fig)
    return out


def write_excerpts() -> Path:
    """Emit verbatim Gemma reasoning, drawn straight from the logs."""
    lines = ["<!-- auto-generated by src/make_report_charts.py; do not hand-edit -->", ""]
    for arm, fn in (("A (ASHA search)", "experiments_armA.jsonl"), ("B (head-only sweep)", "experiments_armB.jsonl")):
        path = ART / fn
        if not path.exists():
            continue
        lines.append(f"**Arm {arm}** — `{fn}`")
        lines.append("")
        for r in load_jsonl(path):
            kept = "kept" if r.get("kept") else "reverted"
            reason = (r.get("reason") or "").strip()
            lines.append(f"- *run {r['run']}* ({kept}): \u201c{reason}\u201d")
        lines.append("")
    out = ART / "gemma_excerpts.md"
    out.write_text("\n".join(lines))
    return out


if __name__ == "__main__":
    a = fig_learning_curves()
    b = fig_results_comparison()
    c = write_excerpts()
    print(f"wrote {a}")
    print(f"wrote {b}")
    print(f"wrote {c}")
